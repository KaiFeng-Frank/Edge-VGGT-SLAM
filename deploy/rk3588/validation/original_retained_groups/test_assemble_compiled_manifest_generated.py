def test_saved_assembly_preserves_export_and_failed_original_quality(tmp_path):
    manifest, manifest_sha, checks, compiles, export = fixture(tmp_path)
    result = A.assemble(manifest, manifest_sha, checks, compiles)
    assert result['schema'] == 'v67_original_VGGT_retained_groups_RKNN_manifest'
    assert result['export_manifest_sha256'] == manifest_sha
    assert result['extra_original_export_metadata'] == export['extra_original_export_metadata']
    assert json.loads(manifest.read_text()) == export
    for index, row in enumerate(result['blocks']):
        assert {k: row[k] for k in export['blocks'][index]} == export['blocks'][index]
        assert row['check_receipt']['file'] == f'check{index}/check.json'
        assert row['compile_receipt']['file'] == f'compile{index}/result.json'
        assert row['rknn']['file'] == f'compile{index}/group.rknn'
        result['blocks'][index]['parents'][0]['sha256'] = 'changed'
        assert export['blocks'][index]['parents'][0]['sha256'] != 'changed'
    assert result['candidate_accepted'] is result['quality_accepted'] is result['realtime_validated'] is False


@pytest.mark.parametrize('failure', ['native_code', 'operation_status', 'missing_operation', 'not_released',
    'cleanup', 'restoration', 'changed_source', 'check_mismatch', 'target19', 'quantization', 'escape', 'model_sha'])
def test_invalid_saved_evidence_rejected(tmp_path, failure):
    manifest, manifest_sha, checks, compiles, _ = fixture(tmp_path)
    index = 3 if failure == 'target19' else 0
    cp, kp = tmp_path / f'compile{index}/result.json', tmp_path / f'check{index}/check.json'
    c, k = json.loads(cp.read_text()), json.loads(kp.read_text())
    if failure == 'native_code': c['operations'][2]['code'] = -1
    elif failure == 'operation_status': c['operations'][2]['status'] = 'attempted'
    elif failure == 'missing_operation': c['operations'].pop()
    elif failure == 'not_released': c['released'] = False
    elif failure == 'cleanup': c['cleanup_errors'] = ['generated cleanup failure']
    elif failure == 'restoration': k['environment_restored'] = False
    elif failure == 'changed_source': k['source_and_input_hashes_after']['generated_only'] = '1'*64
    elif failure == 'check_mismatch': c['check_receipt_sha256'] = 'f'*64
    elif failure == 'target19':
        k['cases'][0]['target_global_source_pair_index'] = 19
        c['cases'] = copy.deepcopy(k['cases'])
    elif failure == 'quantization': c['build_options']['do_quantization'] = True
    elif failure == 'escape': c['rknn']['file'] = '../../group.rknn'
    else: c['rknn']['sha256'] = 'f'*64
    checks[index] = write(kp, k)
    if failure != 'check_mismatch': c['check_receipt_sha256'] = checks[index]
    compiles[index] = write(cp, c)
    with pytest.raises(ValueError):
        A.assemble(manifest, manifest_sha, checks, compiles)


def test_receipt_hash_and_graph_identity_are_pinned(tmp_path):
    manifest, manifest_sha, checks, compiles, _ = fixture(tmp_path)
    with pytest.raises(ValueError):
        A.assemble(manifest, manifest_sha, ['0'*64, *checks[1:]], compiles)
    (tmp_path / 'generated-2.onnx').write_bytes(b'changed generated graph')
    with pytest.raises(ValueError):
        A.assemble(manifest, manifest_sha, checks, compiles)


def test_new_retry_directory_keeps_receipt_and_model_binding(tmp_path):
    manifest, manifest_sha, checks, compiles, _ = fixture(tmp_path)
    (tmp_path / 'compile2').rename(tmp_path / 'compile2-r2')
    selected = ['compile0', 'compile1', 'compile2-r2', 'compile3']
    result = A.assemble(manifest, manifest_sha, checks, compiles, selected)
    assert result['blocks'][2]['compile_receipt']['file'] == 'compile2-r2/result.json'
    assert result['blocks'][2]['rknn']['file'] == 'compile2-r2/group.rknn'


